"""
src/train_libreyolo_task.py

Generic LibreYOLO trainer for any (task, variant) combination, so new
experiments NEVER overwrite previous weights.

Naming contract (deterministic, collision-free between variants):
    weights/<artifact>_<variant>[_<tag>].pt / .onnx
    runs/train_<variant>/<task>[_<tag>]/

Variants — all STRETCH resize, NO letterbox/padding (see src/preprocess_registry.py):
    dfine_nano  -> pretrained LibreDFINEn.pt   imgsz 640  lr0 5e-4
    dfine_small -> pretrained LibreDFINEs.pt   imgsz 640  lr0 3e-4
    picodet_s   -> pretrained LibrePICODETs.pt imgsz 416  lr0 1e-3
    picodet_m   -> pretrained LibrePICODETm.pt imgsz 416  lr0 1e-3

RESOLUTION CONTRACT: imgsz must stay identical across train / ONNX export /
inference (M1_PICODET = 416, M1_DFINE = 640 in src/preprocess_registry.py).

Tasks:
    plate       (Model 1)  -> plate_detector_<variant>.pt
    components  (Model 2)  -> component_detector_<variant>.pt
    charbox     (Model 3A) -> character_box_detector_<variant>.pt
    lao_plate   (Lao M1)   -> plate_detector_lao_<variant>.pt
"""

import shutil
from pathlib import Path

import yaml
from libreyolo import LibreYOLO

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_WEIGHTS_DIR = PROJECT_ROOT / "weights"
RUNS_DIR = PROJECT_ROOT / "runs"

VARIANTS = {
    "dfine_nano":  {"pretrained": "LibreDFINEn.pt",   "imgsz": 640, "lr0": 5e-4},
    "dfine_small": {"pretrained": "LibreDFINEs.pt",   "imgsz": 640, "lr0": 3e-4},
    "picodet_s":   {"pretrained": "LibrePICODETs.pt", "imgsz": 416, "lr0": 1e-3},
    "picodet_m":   {"pretrained": "LibrePICODETm.pt", "imgsz": 416, "lr0": 1e-3},
}

PLATE_DATA_YAML = PROJECT_ROOT / "datasets" / "Thai" / "LPR_2_BBox" / "data.yaml"

# ---------------------------------------------------------------------------
# AUGMENTATION PRESETS
# ---------------------------------------------------------------------------
# WHY THIS BLOCK EXISTS (docs/PREPROCESSING_CONTRACT.md, Law 2 + Law 3)
#
# LibreYOLO ships every geometric and photometric augmentation DISABLED:
#     degrees=0  translate=0  shear=0  perspective=0  flipud=0
#     mosaic_prob=0  hsv_prob=0  mixup=0
# so every model in this repo was fine-tuned with horizontal flip as its ONLY
# augmentation. Three serve-side "fixes" are the direct consequence:
#
#   * 3x LANCZOS4 upscale before M1  -> the detector never saw a small plate
#   * fine_deskew_plate() +/-8 deg    -> the detector never saw a rotated plate
#   * CLAHE on the M1 recovery path  -> the detector never saw a low-contrast plate
#
# All three are preprocessing crutches masking an augmentation gap. Fix the
# cause (train with geometry+photometry) and the crutch becomes removable.
# `none` is kept as the CONTROL arm so the effect can be measured, not assumed.
AUG_PRESETS = {
    # LibreYOLO defaults == every model currently in weights/ (the control arm).
    "none": {},

    # The prescribed retrain preset. Each value is justified by a measurement:
    "plate": {
        "degrees": 6.0,        # measured fine_deskew residual: median 1.25, max 2.75 deg.
                               # 6 deg covers it 2x, for every detector that sees a plate.
        "translate": 0.10,     # M1 boxes sit at cy 0.74 +/- 0.1 in the scene; jitter the frame.
        "shear": 2.0,
        "perspective": 0.0005, # small, so the detector tolerates viewing angle without
                               # learning a geometry serve never produces (warp does it).
        "mosaic_prob": 0.5,    # the SCALE-DEGRADATION arm: replaces the 3x LANCZOS4 upscale.
        "mosaic_scale": (0.3, 1.5),
        "hsv_prob": 0.5,       # the CONTRAST arm: replaces the CLAHE recovery path.
        "flipud": 0.0,         # plates are never upside down; do not teach it.
        "mixup": 0.0,          # mixing two plates invents a layout that never occurs.
        "no_aug_epochs": 10,   # close augmentation for the last 10 epochs (fine-tune phase).
    },
}

TASKS = {
    "plate": {
        "artifact": "plate_detector",
        "dataset_dir": PLATE_DATA_YAML.parent,
        "yaml_name": "data.yaml",  # generated by prepare_bbox_dataset
        "nc": 1,
        "names": ["plate"],
    },
    "components": {
        "artifact": "component_detector",
        "dataset_dir": PROJECT_ROOT / "datasets" / "Thai" / "LPR 2 - Charactor Detection.yolov11",
        "yaml_name": "dfine_data.yaml",
        "nc": 2,
        "names": ["plate_char", "province"],
    },
    "charbox": {
        "artifact": "character_box_detector",
        "dataset_dir": PROJECT_ROOT / "datasets" / "Thai" / "LPR 2 - Character Box Detection.yolov11",
        "yaml_name": "dfine_data.yaml",
        "nc": 1,
        "names": ["char"],
    },
    "lao_plate": {
        "artifact": "plate_detector_lao",
        "dataset_dir": PROJECT_ROOT / "datasets" / "Lao" / "laos plate.v3i.yolov11",
        "yaml_name": "dfine_data.yaml",
        "nc": 2,
        "names": ["0", "plate"],
    },
}


def ensure_plate_dataset():
    if not PLATE_DATA_YAML.exists():
        from prepare_bbox_dataset import convert_polygon_to_bbox
        convert_polygon_to_bbox()


def ensure_clean_yaml(task):
    """Write a data.yaml with absolute paths (LibreYOLO requirement)."""
    cfg = TASKS[task]
    yaml_path = cfg["dataset_dir"] / cfg["yaml_name"]
    if yaml_path.exists() and cfg["yaml_name"] == "data.yaml":
        return yaml_path  # dataset yaml already exists with absolute paths
    data = {
        "train": str((cfg["dataset_dir"] / "train" / "images").resolve()),
        "val":   str((cfg["dataset_dir"] / "valid" / "images").resolve()),
        "test":  str((cfg["dataset_dir"] / "test" / "images").resolve()),
        "nc":    cfg["nc"],
        "names": cfg["names"],
    }
    with open(yaml_path, "w", encoding="utf-8") as f:
        yaml.dump(data, f, sort_keys=False)
    return yaml_path


def _resolve_data_override(task, data):
    """Accept a dataset DIRECTORY or a data.yaml PATH, and return the yaml path with absolute paths."""
    p = Path(data)
    if p.is_file() and p.suffix in (".yaml", ".yml"):
        yaml_path = p
        dir_p = p.parent
    elif p.is_dir():
        dir_p = p
        yaml_path = p / "data.yaml"
    else:
        raise FileNotFoundError(f"data source not found: {p}")

    cfg = TASKS[task]
    clean_yaml = dir_p / "clean_data.yaml"
    
    # Always write clean yaml with absolute paths to avoid Roboflow '../' path resolution failures
    data_dict = {
        "train": str((dir_p / "train" / "images").resolve()),
        "val":   str((dir_p / "valid" / "images").resolve()) if (dir_p / "valid").exists() else str((dir_p / "val" / "images").resolve()),
        "test":  str((dir_p / "test" / "images").resolve()) if (dir_p / "test").exists() else "",
        "nc":    cfg["nc"],
        "names": cfg["names"],
    }
    with open(clean_yaml, "w", encoding="utf-8") as f:
        yaml.dump(data_dict, f, sort_keys=False)
    print(f"   wrote dataset yaml -> {clean_yaml}")
    return clean_yaml


def target_paths(task, variant, tag=""):
    """Deterministic output paths for a (task, variant, tag) combination."""
    cfg = TASKS[task]
    tag_str = f"_{tag.strip().lstrip('_')}" if tag.strip() else ""
    stem = f"{cfg['artifact']}_{variant}{tag_str}"
    return {
        "pt": OUTPUT_WEIGHTS_DIR / f"{stem}.pt",
        "onnx": OUTPUT_WEIGHTS_DIR / f"{stem}.onnx",
        "run_dir": RUNS_DIR / f"train_{variant}" / f"{task}{tag_str}",
    }


def _filter_supported(aug):
    """Drop augmentation keys this LibreYOLO build's train() does not accept."""
    try:
        import dataclasses
        from libreyolo.training.config import TrainConfig
        ok = {f.name for f in dataclasses.fields(TrainConfig)}
    except Exception:
        return dict(aug)
    dropped = sorted(set(aug) - ok)
    if dropped:
        print(f"⚠️  Unsupported aug keys ignored by this LibreYOLO build: {dropped}")
    return {k: v for k, v in aug.items() if k in ok}


def train_libreyolo_task(task, variant, epochs=30, batch=8, imgsz=None,
                         patience=12, device="mps", export_onnx=True, tag="",
                         overwrite=False, aug="none", data=None):
    """Train one (task, variant). Returns True if trained, False if skipped.

    Old weights are preserved: if the target .pt already exists and neither
    a tag nor overwrite=True was given, the task is SKIPPED with guidance.

    aug  : key of AUG_PRESETS, or a dict of raw LibreYOLO augmentation kwargs.
    data : optional dataset dir (or data.yaml path) overriding TASKS[task]["dataset_dir"].
    """
    if task not in TASKS:
        raise KeyError(f"Unknown task '{task}'. Valid: {list(TASKS.keys())}")
    if variant not in VARIANTS:
        raise KeyError(f"Unknown variant '{variant}'. Valid: {list(VARIANTS.keys())}")

    spec = VARIANTS[variant]
    paths = target_paths(task, variant, tag)

    if paths["pt"].exists() and not overwrite:
        print("\n" + "=" * 70)
        print(f"⏭️  SKIP — target already exists (old model preserved):")
        print(f"   {paths['pt'].name}")
        print(f"   → เทรนเวอร์ชันใหม่ไม่ทับของเดิม : เพิ่ม --tag <ชื่อ>  (เช่น --tag v2)")
        print(f"   → บังคับแทนที่ของเดิม           : เพิ่ม --overwrite")
        print("=" * 70)
        return False

    if imgsz is None:
        imgsz = spec["imgsz"]

    pretrained = OUTPUT_WEIGHTS_DIR / spec["pretrained"]
    if not pretrained.exists():
        raise FileNotFoundError(f"Pretrained weights not found: {pretrained}")

    if task == "plate":
        ensure_plate_dataset()
    if data:
        data_yaml = _resolve_data_override(task, data)
    else:
        data_yaml = ensure_clean_yaml(task)
    aug_kwargs = _filter_supported(AUG_PRESETS[aug] if isinstance(aug, str) else aug)
    run_dir = paths["run_dir"]
    run_dir.mkdir(parents=True, exist_ok=True)
    OUTPUT_WEIGHTS_DIR.mkdir(parents=True, exist_ok=True)

    print("\n" + "=" * 70)
    print(f"🚀 LibreYOLO Training — {task} × {variant}" + (f" (tag: {tag})" if tag else ""))
    print(f"   Pretrained: {pretrained.name}")
    print(f"   Dataset   : {Path(data_yaml).parent.name}")
    print(f"   Output    : {paths['pt'].name}")
    print(f"   Augment   : {aug if isinstance(aug, str) else 'custom'} -> {aug_kwargs or 'none (LibreYOLO defaults)'}")
    print(f"   Epochs    : {epochs} | Batch: {batch} | Imgsz: {imgsz} | Patience: {patience}")
    print(f"   ⚠️ RESOLUTION CONTRACT: imgsz={imgsz} must stay the same at ONNX")
    print(f"      export AND inference (stretch resize, no letterbox/padding).")
    print("=" * 70)

    model = LibreYOLO(str(pretrained))
    model.train(
        data=str(data_yaml),
        epochs=epochs,
        batch=batch,
        imgsz=imgsz,
        lr0=spec["lr0"],
        patience=patience,
        device=device,
        project=str(run_dir.parent),
        name=run_dir.name,
        exist_ok=True,
        **aug_kwargs,
    )

    best_pt = run_dir / "weights" / "best.pt"
    if not best_pt.exists():
        candidates = list(run_dir.glob("**/*.pt")) + list(run_dir.glob("**/*.pth"))
        if candidates:
            best_pt = candidates[0]

    if best_pt and best_pt.exists():
        shutil.copy2(best_pt, paths["pt"])
        size_mb = paths["pt"].stat().st_size / 1e6
        print(f"\n✅ Saved best fine-tuned weights → {paths['pt']} ({size_mb:.1f} MB)")

        if export_onnx:
            print(f"Exporting to standalone ONNX (CPU isolated) → {paths['onnx']}...")
            try:
                trained_model = LibreYOLO(str(paths["pt"]), device="cpu")
                trained_model.export(format="onnx", imgsz=imgsz, device="cpu", dynamic=False)
                if hasattr(trained_model, "model_path"):
                    exp_onnx = Path(trained_model.model_path).with_suffix(".onnx")
                    if exp_onnx.exists() and exp_onnx.resolve() != paths["onnx"].resolve():
                        shutil.copy2(exp_onnx, paths["onnx"])
                if paths["onnx"].exists():
                    onnx_mb = paths["onnx"].stat().st_size / 1e6
                    print(f"✅ Exported ONNX → {paths['onnx']} ({onnx_mb:.1f} MB)")
            except Exception as e:
                print(f"⚠️ ONNX export note: {e}")
    else:
        print(f"⚠️ Checkpoint not found in {run_dir}. Check logs.")
        return False

    # Clean up memory and file descriptors between sequential jobs
    try:
        del model
        if 'trained_model' in locals():
            del trained_model
    except Exception:
        pass

    import gc
    gc.collect()
    try:
        import torch
        if torch.backends.mps.is_available():
            torch.mps.empty_cache()
        elif torch.cuda.is_available():
            torch.cuda.empty_cache()
    except Exception:
        pass

    return True


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser(
        description="Train one (task, variant) with LibreYOLO and export ONNX.")
    ap.add_argument("--task", required=True, choices=sorted(TASKS),
                    help="plate | components | charbox | lao_plate")
    ap.add_argument("--variant", required=True, choices=sorted(VARIANTS),
                    help="picodet_s | picodet_m | dfine_nano | dfine_small")
    ap.add_argument("--data", default=None,
                    help="dataset dir or data.yaml override (default: the task's own dir)")
    ap.add_argument("--aug", default="none", choices=sorted(AUG_PRESETS),
                    help="'none' = LibreYOLO defaults (control arm); 'plate' = prescribed retrain aug")
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--imgsz", type=int, default=None,
                    help="MUST match src/preprocess_registry.py and the ONNX export (see RESOLUTION CONTRACT)")
    ap.add_argument("--patience", type=int, default=12)
    ap.add_argument("--device", type=str, default="mps")
    ap.add_argument("--tag", type=str, default="", help="output suffix, e.g. v6 -> <artifact>_<variant>_v6.pt")
    ap.add_argument("--overwrite", action="store_true", help="replace an existing target .pt")
    ap.add_argument("--no-onnx", dest="export_onnx", action="store_false", help="skip ONNX export")
    a = ap.parse_args()

    train_libreyolo_task(
        task=a.task, variant=a.variant, epochs=a.epochs, batch=a.batch, imgsz=a.imgsz,
        patience=a.patience, device=a.device, export_onnx=a.export_onnx, tag=a.tag,
        overwrite=a.overwrite, aug=a.aug, data=a.data,
    )
